"""Detailed conditional coaching instructions; no claims about unmeasured ability."""
from core import metrics, clock_label
from tactics import family


def extended_options(state, tid, goal):
    opp = next(x for x in state['players'] if x != tid)
    recent = [(t, e) for t, e in state['visible'] if t >= state['cutoff'] - 900]
    own = [e for _, e in recent if e.get('team', {}).get('id') == tid]
    other = [e for _, e in recent if e.get('team', {}).get('id') == opp]
    a, b = metrics(state, tid), metrics(state, opp)
    groups = [family(p['position']) for p in state['players'][tid].values()]
    diff = state['goals'][tid] - state['goals'][opp]
    need = diff < 0 or diff == 0 and goal == 'win'
    short = len(state['players'][tid]) < len(state['players'][opp])
    lost = sum(e['type']['name'] in ('Dispossessed', 'Miscontrol') for e in own)
    def corners(events):
        return sum(e.get('pass', {}).get('type', {}).get('name') == 'Corner' for e in events)
    total = a['left'] + a['right'] + a['center']
    concentrated = total >= 5 and max(a['left'], a['right'], a['center']) / total >= .55
    def row(key, title, available, why, tasks, risk, roles, check):
        return dict(key=key, title=title, available=available, why=why, tasks=tasks,
                    risk=risk, roles=roles, check=check)
    return [
        row('central_build', 'Создать опору для выхода через центр', groups.count('central') >= 2,
            f'Подтверждённых центральных полузащитников: {groups.count("central")}. Входов в штрафную: {a["box_entries"]}.',
            ['Один полузащитник открывается перед защитниками, второй занимает следующую линию передачи.',
             'Нападающий удерживает доступную линию паса; не опускать всех адресатов к мячу одновременно.',
             'При закрытом центре вернуть мяч и продолжить через фланг.'],
            'Потеря в центре опаснее потери у боковой линии.', 'Центральные полузащитники и центральные защитники',
            'Сравнить входы в штрафную и удары; отдельно отметить новые потери в центре.'),
        row('switch', 'Переводить атаку на противоположный фланг', concentrated and bool(set(groups) & {'wide', 'full_back'}),
            f'Успешных передач в финальную треть: {total}; распределение слева/центр/справа: '
            f'{a["left"]}/{a["center"]}/{a["right"]}. Направление наших атак не доказывает свободное пространство.',
            ['Привлечь внимание соперника короткими передачами на одной стороне.',
             'Проверить свободного партнёра на другой стороне и переводить только при открытой линии.',
             'Во время перевода центральный полузащитник остаётся на подборе.'],
            'Длинный неподготовленный перевод может привести к перехвату.', 'Фланговые игроки и центральные полузащитники',
            'Сравнить направления продвижений, входы в штрафную и удары.'),
        row('counterpress', 'Короткое давление после потери', not short and groups.count('central') >= 2 and lost >= 2,
            f'За 15 минут зарегистрировано потерь при контроле/отборе: {lost}. Меньшинство: {"да" if short else "нет"}. '
            'Координаты партнёров и расстояния между ними не измерены.',
            ['Ближайший игрок задерживает соперника после потери, партнёр закрывает ближайший короткий пас.',
             'Давить только при поддержке рядом и сохранённой страховке за мячом.',
             'Если соперник вышел из локального давления — немедленно возвращаться в средний блок.'],
            'Без близкой поддержки давление откроет свободную зону.', 'Ближайшие к потере полузащитники',
            'Отметить потери, после которых соперник вошёл в штрафную; не считать все отборы результатом плана.'),
        row('deep_block', 'Временно снизить блок и восстановить структуру', short or diff > 0 and b['box_entries'] >= 3,
            f'Численность: {len(state["players"][tid])}:{len(state["players"][opp])}; '
            f'входов соперника в штрафную за 15 минут: {b["box_entries"]}.',
            ['Сблизить линии, закрыть центральный коридор и направлять соперника наружу.',
             'Оставить доступного адресата для выхода после отбора.',
             'При безопасном владении поднимать блок вместе, не оставаться у ворот постоянно.'],
            'Продолжительная оборона у штрафной повышает нагрузку и число повторных атак.',
            'Защитники, полузащитники и один адресат впереди', 'Сравнить частоту входов соперника и собственных ударов.'),
        row('attacking_corner', 'Организовать следующий угловой в атаке', corners(own) > 0,
            f'Наших угловых за 15 минут: {corners(own)}. Рост, игра головой и качество подачи не оценены.',
            ['Перед подачей распределить роли: подающий, адресаты, подбор и страховка.',
             'Сохранять игрока на подборе и страховку от быстрого выхода соперника.',
             'При закрытой подаче проверить короткий розыгрыш; решение о варианте принимает подающий.'],
            'Чрезмерное число игроков у ворот соперника оголит страховку.', 'Подающий, адресаты и игроки на подборе',
            'При следующем угловом проверить завершение и наличие контратаки; если углового не было — данных для оценки нет.'),
        row('defending_corner', 'Распределить роли при угловом соперника', corners(other) > 0,
            f'Угловых соперника за 15 минут: {corners(other)}. Индивидуальная эффективность в воздухе не измерена.',
            ['До подачи распределить опеку адресатов, защиту ключевых зон и подбор за штрафной.',
             'После первого касания продолжать сопровождать соперников до выхода мяча из опасной зоны.',
             'Оставить доступный выход после отбора, если позволяет численность.'],
            'Смешанная или персональная опека требует заранее согласованных передач ответственности.',
            'Защитники и полузащитники на подборе',
            'Оценивать только следующие угловые: удары, повторные подачи и подборы; без новых угловых вывод не делать.')]


def detailed_instructions(state, tid, option):
    key = option['key']
    needs = {
        'center': {'center_back', 'central'}, 'flank': {'full_back', 'wide', 'central'},
        'width': {'wide', 'full_back', 'striker'}, 'transition': {'striker', 'central'},
        'press': {'striker', 'creator', 'central'}, 'control': {'central', 'full_back'},
        'central_build': {'central', 'center_back'}, 'switch': {'central', 'wide', 'full_back'},
        'counterpress': {'central', 'creator', 'wide'}, 'deep_block': {'center_back', 'central', 'striker'},
        'attacking_corner': {'wide', 'creator', 'central', 'center_back', 'striker'},
        'defending_corner': {'center_back', 'full_back', 'central'}}.get(key, set(option.get('role_groups', [])))
    duties = {
        'keeper': 'Предложить безопасный первый пас; при закрытых коротких адресатах согласовать дальний выход и подбор.',
        'center_back': 'Страховать партнёра, закрывать передачу за спину; выходить к мячу поочерёдно.',
        'central': 'Закрывать передачу между линиями, предлагать первый пас после отбора и сохранять подбор.',
        'full_back': 'Контролировать свой край; подключаться только при страховке центрального полузащитника.',
        'wide': 'Давать ширину с мячом; после потери возвращаться к своему краю и помогать защитнику.',
        'striker': 'Сохранять адресата впереди, открываться под первый пас и не опускаться одновременно со всем центром.',
        'creator': 'Открывать линию передачи между линиями; после потери перекрывать ближайший короткий пас.'}
    overrides = {
        'flank': {'full_back': 'Встречать мяч на активном краю, если партнёр страхует; не выходить одновременно с ним.',
                  'wide': 'Помогать крайнему защитнику на активной стороне; при переводе возвращаться в свою зону.',
                  'central': 'Страховать смещение к краю и сохранять закрытым центральный коридор.'},
        'central_build': {'central': 'Чередовать открывания: один перед защитой, второй выше; не занимать одну линию паса.',
                          'center_back': 'Искать открытого полузащитника; при закрытой линии переводить через партнёра.'},
        'switch': {'wide': 'Держать ширину на дальней стороне и показать открывание перед переводом.',
                   'central': 'Связать стороны через безопасную передачу; после перевода сохранить подбор.'},
        'press': {'striker': 'По обратному пасу закрывать удобное направление первого паса; без поддержки не начинать давление.',
                  'central': 'Поддержать первую линию, сохраняя страховку центра; при её проходе возвращаться в блок.'},
        'transition': {'striker': 'После отбора открыть безопасную линию первого паса и удержать мяч до подхода поддержки.',
                       'central': 'Дать первый надёжный пас и поддержать выход; один партнёр остаётся страховать.'},
        'attacking_corner': {'center_back': 'Перед подачей согласовать с тренером роль адресата либо страховки; не уходить всем защитникам вперёд.',
                             'central': 'Согласовать подбор и страховку контратаки; не занимать одну зону с партнёром.',
                             'striker': 'Согласовать зону завершения; после первого касания продолжить борьбу за повторную передачу.'},
        'defending_corner': {'center_back': 'До подачи согласовать зону или персональную опеку; сопровождать до устранения угрозы.',
                             'full_back': 'Согласовать ближнюю зону и передачу опеки; не оставлять адресата при втором мяче.',
                             'central': 'Контролировать подбор и повторную подачу; после отбора предложить безопасный выход.'}}
    assignments = [{'Игрок': p['name'], 'Подтверждённая позиция': p['position'],
                    'Задача': overrides.get(key, {}).get(family(p['position']), duties[family(p['position'])])}
                   for p in state['players'][tid].values() if family(p['position']) in needs]
    # Named players are role-compatible participants, never inferred skill rankings.
    phases = {
        'С мячом': 'Поддерживать две доступные линии передачи; при закрытом продвижении сохранять мяч через партнёра сзади.',
        'Без мяча': 'Сохранять расстояния между линиями и страховать игрока, выходящего к мячу.',
        'После потери': 'Ближайший игрок задерживает продвижение; остальные сначала закрывают центр и передачу за спину.',
        'После отбора': 'Проверить свободного партнёра впереди; при отсутствии безопасного паса закрепить владение.'}
    if key in ('press', 'counterpress'):
        phases['Без мяча'] = 'Давить согласованно только по сигналу: обратный пас, плохой приём или локальная потеря с поддержкой рядом.'
        phases['После потери'] = 'Не начинать одиночную погоню. Если рядом нет поддержки — вернуться в согласованный блок.'
    if key in ('center', 'deep_block', 'defending_corner'):
        phases['Без мяча'] = 'Защитить центральную зону и подбор; не выводить нескольких игроков одновременно на мяч.'
    if key in ('width', 'switch'):
        phases['С мячом'] = 'Дать ширину с двух сторон, подключать только одного крайнего защитника; проверять открытый перевод.'
    if key == 'transition':
        phases['После отбора'] = 'Искать нападающего первым надёжным пасом и поддерживать выход поочерёдно.'
    if key in ('attacking_corner', 'defending_corner'):
        phases['Без мяча'] = 'До подачи согласовать персональную ответственность, зонную страховку и игрока на подборе.'
    relevant = []
    for tick, event in reversed(state['visible']):
        if tick < state['cutoff'] - 900:
            continue
        kind = event['type']['name']
        corner = event.get('pass', {}).get('type', {}).get('name') == 'Corner'
        use = corner if 'corner' in key else kind in ('Shot', 'Dispossessed', 'Miscontrol')
        if use:
            relevant.append({'Время': clock_label(event), 'Событие': 'Угловой' if corner else
                             {'Shot': 'Удар', 'Dispossessed': 'Потеря при отборе', 'Miscontrol': 'Ошибка контроля'}.get(kind, kind),
                             'Команда': event.get('team', {}).get('name', ''),
                             'Игрок': event.get('player', {}).get('name', '—')})
        if len(relevant) == 5:
            break
    return {'phases': phases, 'assignments': assignments, 'events': option.get('event_evidence', list(reversed(relevant))),
            'stop': 'Пересмотреть немедленно после гола, удаления или замены. '
                    'Отменить действие, если не удаётся сохранить страховку или игроки не могут выполнять назначенные роли.',
            'limits': 'Роли и события подтверждены записью. Реальные расстояния, физическая готовность, '
                      'скорость, качество опеки и выполнение инструкций не измерены.'}
